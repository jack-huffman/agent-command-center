/**
 * The area indexes (D-???). The Command Center's code lives in one module per area, and an area module
 * that declares `export const area` registers itself: its CLI commands and help, its webview sections, the
 * messages its page sends, the commands its page may ask for. Each folder below gets an index that imports
 * every area module in it, so no file lists the areas by hand and a new area edits only its own files.
 *
 * npm run build writes the indexes before it bundles anything. They're committed, because typecheck runs
 * before the build in npm run check; scripts/test/areas.test.ts fails when one is stale.
 *
 *   node scripts/areas.ts           write the indexes that changed
 *   node scripts/areas.ts --check   list the stale ones, writing nothing; exit 1 if there are any
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export interface AreaFolder {
  /** The folder, from the repo's root. Only its own files count, not subfolders'. */
  dir: string;
  /** The index's file name in it. */
  index: string;
  /** Types each area may also export, gathered into one union of that name in the index. */
  unions?: string[];
}

export const FOLDERS: AreaFolder[] = [
  { dir: 'packages/cli/src/commands', index: 'index.ts' },
  { dir: 'extension/src', index: 'areas.ts' },
  { dir: 'extension/src/model', index: 'areas.ts', unions: ['Message'] },
  { dir: 'extension/webview', index: 'areas.ts' },
];

export const HEADER = '// Generated by scripts/areas.ts from the modules here that declare `export const area`. Don\'t edit it:\n// npm run build writes it again, and scripts/test/areas.test.ts fails when it\'s stale.';

/** A module's name as a variable: task-page.ts is taskPage. */
const varName = (file: string): string => file.replace(/\.ts$/, '').replace(/-(\w)/g, (_, c: string) => c.toUpperCase());

/** The area modules in a folder, by file name. */
export function areaFiles(folder: AreaFolder, root = ROOT): string[] {
  const dir = join(root, folder.dir);
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => f.endsWith('.ts') && f !== folder.index && /^export const area\b/m.test(readFileSync(join(dir, f), 'utf8'))).sort();
}

/** What a folder's index should hold. */
export function indexText(folder: AreaFolder, root = ROOT): string {
  const files = areaFiles(folder, root);
  const dir = join(root, folder.dir);
  const lines = [HEADER, ...files.map((f) => `import { area as ${varName(f)} } from './${f}';`), ''];
  lines.push(`export const AREAS = [${files.map(varName).join(', ')}];`);
  for (const u of folder.unions ?? []) {
    const having = files.filter((f) => new RegExp(`^export (type|interface) ${u}\\b`, 'm').test(readFileSync(join(dir, f), 'utf8')));
    lines.push(`export type ${u} =\n${having.map((f) => `  | import('./${f}').${u}`).join('\n')};`);
  }
  return `${lines.join('\n')}\n`;
}

/** Writes each index that differs from what it should hold, and returns those that did (or would, with check). */
export function writeAreas(check = false, root = ROOT): string[] {
  const stale: string[] = [];
  for (const folder of FOLDERS) {
    const file = join(root, folder.dir, folder.index);
    if (!existsSync(file) && !areaFiles(folder, root).length) continue;
    const text = indexText(folder, root);
    if (existsSync(file) && readFileSync(file, 'utf8') === text) continue;
    stale.push(join(folder.dir, folder.index));
    if (!check) writeFileSync(file, text);
  }
  return stale;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const stale = writeAreas(check);
  if (check && stale.length) {
    console.error(`Stale: ${stale.join(', ')}. Run npm run build.`);
    process.exitCode = 1;
  } else console.log(stale.length ? `${check ? 'stale' : 'updated'} ${stale.join(', ')}` : 'area indexes up to date');
}
